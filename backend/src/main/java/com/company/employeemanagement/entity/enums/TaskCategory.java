package com.company.employeemanagement.entity.enums;

/**
 * Predefined categories for company tasks.
 *
 * @author Employee Management Portal Team
 */
public enum TaskCategory {

    /** Software development and feature implementation work. */
    DEVELOPMENT,

    /** Quality assurance, unit testing, and integration testing. */
    TESTING,

    /** Technical or user-facing documentation. */
    DOCUMENTATION,

    /** Infrastructure, CI/CD, deployment, and operations work. */
    DEVOPS,

    /** Human resources and people-management tasks. */
    HR,

    /** Customer or internal support, bug fixes, and helpdesk. */
    SUPPORT,

    /** Research, investigation, and proof-of-concept work. */
    RESEARCH,

    /** Catch-all for tasks that do not fit other categories. */
    OTHER
}
